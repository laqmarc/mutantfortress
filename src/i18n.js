const TABLES = { en: EN, ca: CA };
export const LANGS = ['en', 'ca'];
export const LANG_LABEL = { en: 'EN', ca: 'CA' };

let lang = 'en';
const listeners = new Set();

/** Mapeja un codi de locale (ex. "ca-ES", "es-419") a un idioma suportat. */
export function normalizeLang(locale) {
  if (typeof locale !== 'string') return 'en';
  return locale.toLowerCase().startsWith('ca') ? 'ca' : 'en';
}

export function getLang() { return lang; }

export function setLang(next) {
  const l = TABLES[next] ? next : 'en';
  if (l === lang) return;
  lang = l;
  // les eines de tools/ importen aquest mòdul des de Node, on no hi ha DOM
  if (typeof document !== 'undefined') document.documentElement.lang = l;
  for (const fn of listeners) fn(l);
}

export function onLangChange(fn) { listeners.add(fn); }

/** Tradueix una clau i hi interpola {params}. Si falta, cau a l'anglès. */
export function t(key, params) {
  let v = TABLES[lang][key];
  if (v === undefined) v = EN[key];
  if (v === undefined) return key;
  if (Array.isArray(v) || !params) return v;
  return v.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? params[k] : m));
}

